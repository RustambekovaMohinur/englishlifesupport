"""
Precise Vocabulary Companion PDF & Text Extraction Service.

Specifically designed for "Upstream Advanced Companion" and similar companion-style
vocabulary resources. Extracts clean dictionary entries:
- word: Clean base headword, phrase, or idiom (stripped of index numbers, phonetics, and POS)
- definition: Exact English definition (everything after '=' and before foreign translation '/')
- translation: Natural, high-quality Uzbek translation generated by AI

Filters out all clutter:
- Index numbers (e.g. "1.1", "1.12")
- Phonetic transcriptions and parts of speech (e.g. "/ˈfɔːsaɪt/ (n)")
- Polish / foreign translations (e.g. "/ dalekowzroczność...")
- Example sentences ("e.g. ...")
- Derivatives ("Der.: ...")
- Section headers ("lead-in (p. 7)", "Reading (pp. 8-9)", page numbers)
"""

import base64
import io
import json
import logging
import re
from typing import Any

from app.services.ai_examiner import (
    execute_gemini_generate_content,
    get_gemini_api_key,
    clean_uzbek_text,
    infer_pos_and_clean_word,
)

logger = logging.getLogger(__name__)

COMPANION_PROMPT = """You are an expert bilingual lexicographer.
Extract vocabulary entries from the provided companion text.

Input line example:
"1.3 foresight /ˈfɔːsaɪt/ (n) = the ability to see what is likely to happen in the future and to take appropriate action / dalekowzroczność
e.g. They had the foresight to prepare...
Der.: diplomatic"

Desired output object:
{
  "word": "foresight",
  "definition": "the ability to see what is likely to happen in the future and to take appropriate action",
  "translation": "oldindan ko'ra bilish, uzoqni ko'ra olish"
}

STRICT EXTRACTION RULES:
1. "word": Clean base headword, phrase, or idiom without index numbers or pronunciation (e.g. "foresight", "block out a thought", "diplomacy").
2. "definition": The exact English definition from the text (everything after "=" and before the foreign translation/slash).
3. "translation": Natural, accurate Uzbek translation of the headword generated by AI (since the PDF has Polish or other foreign translations; do NOT output Polish words, generate the proper Uzbek translation).
4. STRICTLY OMIT / STRIP OUT:
   - Index numbers (e.g. "1.1", "1.12")
   - Phonetic transcriptions and parts of speech (e.g. "/ˈfɔːsaɪt/ (n)")
   - Polish/foreign language translations (e.g. "/ dalekowzroczność, umiejętność...")
   - Example sentences starting with "e.g."
   - Derivatives starting with "Der.:"
   - Section headers ("lead-in (p. 7)", "Reading (pp. 8-9)", unit titles, page numbers).

Return a JSON array of such objects. Output pure JSON without markdown code fences."""


def extract_text_from_pdf_bytes(file_bytes: bytes) -> str:
    """Extracts raw text from PDF bytes using pypdf."""
    try:
        import pypdf

        reader = pypdf.PdfReader(io.BytesIO(file_bytes))
        pages_text: list[str] = []
        for idx, page in enumerate(reader.pages):
            text = page.extract_text() or ""
            if text.strip():
                pages_text.append(text)
        return "\n\n".join(pages_text).strip()
    except Exception as exc:
        logger.warning("pypdf text extraction failed: %s", exc)
        return ""


def clean_companion_headword(raw_headword: str) -> str:
    """
    Strips index numbers, phonetics, parts of speech, and typography clutter.
    Example: '1.3 foresight /ˈfɔːsaɪt/ (n)' -> 'foresight'
    Example: '1.1 block out a thought' -> 'block out a thought'
    """
    s = raw_headword.strip()
    # Strip index numbers like '1.3', '1.12', '2.14.', '1.'
    s = re.sub(r"^\s*\d+(\.\d+)*\.?\s*", "", s)
    # Strip phonetic transcriptions e.g. /ˈfɔːsaɪt/, /.../
    s = re.sub(r"/[^/\n\r]+/", "", s)
    # Strip parts of speech in parentheses e.g. (n), (v), (adj), (adv), (phr v), (idm)
    s = re.sub(
        r"\s*\((n|v|adj|adv|phr\s*v|phrasal\s*verb|idm|idiom|prep|pron|conj|interj|c|u|pl)\.?\)\s*",
        " ",
        s,
        flags=re.IGNORECASE,
    )
    # Strip residual punctuation
    s = re.sub(r"[^\w\s'-]", " ", s)
    # Normalize whitespace
    s = re.sub(r"\s+", " ", s).strip()
    return s


def clean_companion_definition(raw_def: str) -> str:
    """
    Extracts the clean English definition:
    - Everything after '='
    - Before foreign translation '/'
    - Stripping 'e.g.', 'Der.:' and linebreaks
    """
    s = raw_def.strip()
    if "=" in s:
        s = s.split("=", 1)[1].strip()

    # Cut off Polish/foreign translations starting with slash
    if "/" in s:
        s = s.split("/", 1)[0].strip()

    # Cut off example sentences or derivatives
    s = re.split(r"\b(?:e\.g\.|Der\.:|Derivatives?:)\b", s, flags=re.IGNORECASE)[0].strip()

    # Normalize whitespace
    s = re.sub(r"\s+", " ", s).strip()
    return s.strip(" ;,-")


def is_companion_format(text: str) -> bool:
    """
    Detects if the content matches 'Upstream Companion' style:
    has index numbers like 1.1, '=', '/ foreign', 'e.g.', or 'Der.:'
    """
    if not text:
        return False
    companion_indicators = [
        bool(re.search(r"\b\d+\.\d+\s+[a-zA-Z]", text)),
        "=" in text and ("/" in text or "e.g." in text or "Der.:" in text),
        "lead-in (p." in text.lower(),
    ]
    return sum(companion_indicators) >= 1


def parse_companion_text_locally(text: str) -> list[dict[str, Any]]:
    """
    High-precision local heuristic parser for companion entries.
    Handles entries when Gemini API is offline or quota is exceeded.
    """
    if not text:
        return []

    entries: list[dict[str, Any]] = []
    lines = text.splitlines()

    # Pre-clean lines: omit section headers
    cleaned_lines: list[str] = []
    for line in lines:
        l_str = line.strip()
        if not l_str:
            continue
        # Skip section headers
        if re.search(
            r"^(?:lead-in|reading|language focus|listening|speaking|writing|unit\s+\d+|module\s+\d+)\s*\((?:p|pp)\.?\s*\d+(?:-\d+)?\)",
            l_str,
            re.IGNORECASE,
        ):
            continue
        if re.match(r"^\d+$", l_str):  # pure page numbers
            continue
        cleaned_lines.append(l_str)

    joined = "\n".join(cleaned_lines)

    # Match blocks starting with index or headword followed by '='
    # Regex finds: (\d+\.\d+\s+[^\n=]+?)\s*=\s*([^\n]+(?:\n(?!\d+\.\d+\s+)[^\n]+)*)
    pattern = re.compile(
        r"(?:^|\n)\s*(\d+\.\d+\s+[^\n=]+?)\s*=\s*(.+?)(?=(?:\n\s*\d+\.\d+\s+[^\n=]+?\s*=)|\Z)",
        re.DOTALL,
    )

    matches = pattern.findall(joined)
    for raw_hw, raw_body in matches:
        word = clean_companion_headword(raw_hw)
        if not word or len(word) < 2:
            continue

        definition = clean_companion_definition(raw_body)
        if not definition:
            continue

        clean_w, pos = infer_pos_and_clean_word(word)

        entries.append({
            "word": clean_w,
            "definition": definition,
            "translation": "",
            "uzbek_translation": "",
            "custom_translation": "",
            "pos": pos,
            "part_of_speech": pos,
            "example_sentence": "",
            "example": "",
            "phonetic": "",
            "audio_us_url": f"https://ssl.gstatic.com/dictionary/static/sounds/20200429/{clean_w.lower().replace(' ', '_')}--_us_1.mp3",
            "ai_generated": False,
            "fallback_used": True,
            "source": "companion_local_parser",
        })

    return entries


async def extract_companion_vocabulary(
    raw_text: str | None = None,
    file_bytes: bytes | None = None,
    file_name: str | None = None,
    mime_type: str | None = None,
) -> list[dict[str, Any]]:
    """
    Extracts vocabulary items from Upstream Companion style PDF or text
    using Gemini AI with exact schema:
    [
      {
        "word": "foresight",
        "definition": "the ability to see what is likely to happen in the future and to take appropriate action",
        "translation": "oldindan ko'ra bilish, uzoqni ko'ra olish"
      }
    ]
    Includes robust fallback to local regex parser if AI is unreachable.
    """
    extracted_text = (raw_text or "").strip()
    is_pdf = False

    if file_bytes:
        f_name_lower = (file_name or "").lower()
        if f_name_lower.endswith(".pdf") or (mime_type and "pdf" in mime_type.lower()):
            is_pdf = True
            pdf_text = extract_text_from_pdf_bytes(file_bytes)
            if pdf_text:
                extracted_text = (extracted_text + "\n\n" + pdf_text).strip()
        elif f_name_lower.endswith((".txt", ".csv")) or (mime_type and "text" in mime_type.lower()):
            try:
                decoded = file_bytes.decode("utf-8")
            except UnicodeDecodeError:
                decoded = file_bytes.decode("latin-1", errors="replace")
            extracted_text = (extracted_text + "\n\n" + decoded).strip()

    if not extracted_text and not (is_pdf and file_bytes):
        raise ValueError("Please provide companion text or upload a valid companion PDF file.")

    api_key = get_gemini_api_key()

    # Attempt 1: Gemini AI extraction
    if api_key:
        try:
            parts: list[dict] = []

            # If we extracted rich text from PDF, prefer sending text directly (faster, more accurate)
            if extracted_text:
                parts.append({
                    "text": f"{COMPANION_PROMPT}\n\nINPUT COMPANION TEXT TO EXTRACT:\n\"\"\"\n{extracted_text[:40000]}\n\"\"\""
                })
            elif is_pdf and file_bytes:
                # Scanned PDF without text layer: use multimodal inlineData
                if len(file_bytes) > 20 * 1024 * 1024:
                    raise ValueError("PDF file exceeds maximum allowed size of 20 MB.")
                b64_pdf = base64.b64encode(file_bytes).decode("utf-8")
                parts.append({
                    "inlineData": {
                        "mimeType": "application/pdf",
                        "data": b64_pdf,
                    }
                })
                parts.append({"text": COMPANION_PROMPT})

            payload = {
                "contents": [{"parts": parts}],
                "generationConfig": {
                    "responseMimeType": "application/json",
                    "temperature": 0.1,
                },
            }

            resp, last_error = await execute_gemini_generate_content(
                payload=payload,
                api_key=api_key,
                timeout=16.0,
                max_backoff_retries=1,
                backoff_delays=(1.0,),
            )

            if resp and resp.status_code == 200:
                data = resp.json()
                candidates = data.get("candidates", [])
                if candidates:
                    content_parts = candidates[0].get("content", {}).get("parts", [])
                    if content_parts:
                        raw_llm_text = content_parts[0].get("text", "").strip()
                        if "```" in raw_llm_text:
                            raw_llm_text = re.sub(r"^```(?:json)?\s*", "", raw_llm_text, flags=re.IGNORECASE)
                            raw_llm_text = re.sub(r"\s*```$", "", raw_llm_text)
                        raw_llm_text = raw_llm_text.strip()

                        parsed = json.loads(raw_llm_text)
                        items_list = parsed if isinstance(parsed, list) else (parsed.get("words") or parsed.get("items") or [])

                        results: list[dict[str, Any]] = []
                        for item in items_list:
                            if not isinstance(item, dict):
                                continue
                            raw_word = str(item.get("word") or "").strip()
                            clean_word = clean_companion_headword(raw_word)
                            if not clean_word:
                                continue

                            definition = str(item.get("definition") or "").strip()
                            translation = clean_uzbek_text(
                                str(item.get("translation") or item.get("uzbek_translation") or "")
                            )

                            clean_w, pos = infer_pos_and_clean_word(clean_word)
                            slug = re.sub(r"[^a-zA-Z0-9]+", "_", clean_w.lower()).strip("_")

                            results.append({
                                "word": clean_w,
                                "definition": definition,
                                "translation": translation,
                                "uzbek_translation": translation,
                                "custom_translation": translation,
                                "pos": pos,
                                "part_of_speech": pos,
                                "example_sentence": "",
                                "example": "",
                                "phonetic": "",
                                "audio_us_url": f"https://ssl.gstatic.com/dictionary/static/sounds/20200429/{slug}--_us_1.mp3",
                                "ai_generated": True,
                                "fallback_used": False,
                                "source": "gemini_ai",
                            })

                        if results:
                            logger.info("Companion extraction succeeded: extracted %d items via Gemini AI.", len(results))
                            return results
        except Exception as exc:
            logger.warning("Gemini companion extraction encountered error (%s); trying local parser fallback.", exc)

    # Attempt 2: High-precision local parser fallback
    if extracted_text:
        local_items = parse_companion_text_locally(extracted_text)
        if local_items:
            logger.info("Local companion fallback parser extracted %d items.", len(local_items))
            return local_items

    raise ValueError("Could not extract vocabulary entries from the companion file. Please ensure it contains 'word = definition' entries.")
