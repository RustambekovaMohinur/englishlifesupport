logger = logging.getLogger(__name__)

COMPANION_PROMPT = """You are an expert bilingual lexicographer and document layout parser.
Extract vocabulary entries from the provided textbook companion text or PDF document.

Input line example:
"1.3 foresight /ˈfɔːsaɪt/ (n) = the ability to see what is likely to happen in the future and to take appropriate action / dalekowzroczność
e.g. They had the foresight to prepare themselves financially.
Der.: diplomatic"

Desired output JSON structure:
[
  {
    "word": "foresight",
    "pos": "noun",
    "definition": "the ability to see what is likely to happen in the future and to take appropriate action",
    "translation": "oldindan ko'ra bilish, uzoqni ko'ra olish",
    "example_sentence": "They had the foresight to prepare themselves financially."
  }
]

STRICT EXTRACTION RULES:
1. "word": Clean base headword, phrase, or idiom without index numbers or pronunciation (e.g. "foresight", "block out a thought", "diplomacy").
2. "pos": Part of speech strictly normalized to one of: "noun", "verb", "adjective", "adverb", "phrase", "idiom", "phrasal_verb".
3. "definition": The exact English definition from the text (everything after "=" and before the foreign translation/slash).
4. "translation": Natural, accurate Uzbek translation of the headword generated by AI (since the PDF has Polish or other foreign translations; do NOT output Polish words, generate the proper Uzbek translation).
5. "example_sentence": The example sentence from the text (following "e.g.") or a natural Cambridge context sentence illustrating the word if "e.g." is absent.
6. STRICTLY OMIT / STRIP OUT:
   - Index numbers (e.g. "1.1", "1.12", "1.57")
   - Phonetic transcriptions and parts of speech inside the word (e.g. "/ˈfɔːsaɪt/ (n)")
   - Polish/foreign language translations (e.g. "/ dalekowzroczność, umiejętność...")
   - Derivatives starting with "Der.:"
   - Section headers ("lead-in (p. 7)", "Reading (pp. 8-9)", unit titles like "UNIT 1", page numbers).

Return a STRICT JSON array of objects conforming to the schema above. Output pure JSON without markdown code fences."""


def extract_text_from_pdf_bytes(file_bytes: bytes) -> str:
    """Extracts raw text stream from PDF bytes using pypdf."""
    try:
        import pypdf

        reader = pypdf.PdfReader(io.BytesIO(file_bytes))
        pages_text: list[str] = []
        for page in reader.pages:
            text = page.extract_text() or ""
            if text.strip():
                pages_text.append(text)
        return "\n\n".join(pages_text).strip()
    except Exception as exc:
        logger.warning("pypdf text extraction failed: %s", exc)
        return ""


def clean_companion_headword(raw_headword: str) -> str:
    """
    Strips index numbers, phonetics, parts of speech, and typography clutter.
    Example: '1.3 foresight /ˈfɔːsaɪt/ (n)' -> 'foresight'
    Example: '1.1 block out a thought' -> 'block out a thought'
    """
    s = raw_headword.strip()
    # Strip index numbers like '1.3', '1.12', '2.14.', '1.'
    s = re.sub(r"^\s*\d+(\.\d+)*\.?\s*", "", s)
    # Strip phonetic transcriptions e.g. /ˈfɔːsaɪt/, /.../
    s = re.sub(r"/[^/\n\r]+/", "", s)
    # Strip parts of speech in parentheses e.g. (n), (v), (adj), (adv), (phr v), (idm)
    s = re.sub(
        r"\s*\((?:n|v|adj|adv|phr\s*v|phrasal\s*verb|idm|idiom|prep|pron|conj|interj|c|u|pl)\.?\)\s*",
        " ",
        s,
        flags=re.IGNORECASE,
    )
    # Strip residual punctuation except hyphens/apostrophes
    s = re.sub(r"[^\w\s'-]", " ", s)
    # Normalize whitespace
    s = re.sub(r"\s+", " ", s).strip()
    return s


def is_companion_format(text: str) -> bool:
    """
    Detects if the content matches 'Upstream Companion' style:
    has index numbers like 1.1, '=', '/ foreign', 'e.g.', or 'Der.:'
    """
    if not text:
        return False
    companion_indicators = [
        bool(re.search(r"\b\d+\.\d+\s+[a-zA-Z]", text)),
        "=" in text and ("/" in text or "e.g." in text or "Der.:" in text),
        "lead-in (p." in text.lower(),
        "reading (pp." in text.lower(),
    ]
    return sum(companion_indicators) >= 1


async def extract_companion_vocabulary(
    raw_text: str | None = None,
    file_bytes: bytes | None = None,
    file_name: str | None = None,
    mime_type: str | None = None,
) -> list[dict[str, Any]]:
    """
    STRICT GEMINI AI MULTIMODAL EXTRACTION:
    Routes companion documents and PDFs directly to Gemini AI.
    Never falls back to broken local regex parsers for PDF/companion inputs.
    """
    extracted_text = (raw_text or "").strip()
    is_pdf = False

    if file_bytes:
        f_name_lower = (file_name or "").lower()
        if f_name_lower.endswith(".pdf") or (mime_type and "pdf" in mime_type.lower()):
            is_pdf = True
            pdf_text = extract_text_from_pdf_bytes(file_bytes)
            if pdf_text:
                extracted_text = (extracted_text + "\n\n" + pdf_text).strip()
        elif f_name_lower.endswith((".txt", ".csv")) or (mime_type and "text" in mime_type.lower()):
            try:
                decoded = file_bytes.decode("utf-8")
            except UnicodeDecodeError:
                decoded = file_bytes.decode("latin-1", errors="replace")
            extracted_text = (extracted_text + "\n\n" + decoded).strip()

    if not extracted_text and not (is_pdf and file_bytes):
        raise ValueError("Please provide companion text or upload a valid companion PDF file.")

    api_key = get_gemini_api_key()
    if not api_key:
        raise ValueError(
            "GEMINI_API_KEY is not configured on the server. Please add your GEMINI_API_KEY to backend/.env to enable Gemini AI PDF vocabulary extraction."
        )

    parts: list[dict] = []

    # If it is a PDF document, provide multimodal inlineData so Gemini visually sees columns and formatting
    if is_pdf and file_bytes:
        if len(file_bytes) > 20 * 1024 * 1024:
            raise ValueError("PDF file exceeds maximum allowed size of 20 MB.")
        b64_pdf = base64.b64encode(file_bytes).decode("utf-8")
        parts.append({
            "inlineData": {
                "mimeType": "application/pdf",
                "data": b64_pdf,
            }
        })
        if extracted_text:
            parts.append({
                "text": f"{COMPANION_PROMPT}\n\nDocument text stream:\n\"\"\"\n{extracted_text[:40000]}\n\"\"\""
            })
        else:
            parts.append({"text": COMPANION_PROMPT})
    else:
        parts.append({
            "text": f"{COMPANION_PROMPT}\n\nINPUT COMPANION TEXT TO EXTRACT:\n\"\"\"\n{extracted_text[:40000]}\n\"\"\""
        })

    payload = {
        "contents": [{"parts": parts}],
        "generationConfig": {
            "responseMimeType": "application/json",
            "temperature": 0.1,
        },
    }

    # High timeout (45s) for multimodal PDF analysis with exponential retry
    resp, last_error = await execute_gemini_generate_content(
        payload=payload,
        api_key=api_key,
        timeout=45.0,
        max_backoff_retries=2,
        backoff_delays=(1.5, 3.0),
    )

    if not resp or resp.status_code != 200:
        error_msg = last_error or (f"HTTP {resp.status_code}" if resp else "No response from Gemini API")
        if "429" in error_msg or "quota" in error_msg.lower() or "resource_exhausted" in error_msg.lower():
            raise ValueError(
                "Gemini AI quota limit reached (HTTP 429). Please wait a moment or configure an additional GEMINI_API_KEY."
            )
        raise ValueError(f"Gemini AI extraction error: {error_msg}")

    data = resp.json()
    candidates = data.get("candidates", [])
    if not candidates:
        raise ValueError("Gemini AI returned empty candidates. Please check document contents.")

    content_parts = candidates[0].get("content", {}).get("parts", [])
    if not content_parts:
        raise ValueError("Gemini AI returned empty response parts.")

    raw_llm_text = content_parts[0].get("text", "").strip()
    if "```" in raw_llm_text:
        raw_llm_text = re.sub(r"^```(?:json)?\s*", "", raw_llm_text, flags=re.IGNORECASE)
        raw_llm_text = re.sub(r"\s*```$", "", raw_llm_text)
    raw_llm_text = raw_llm_text.strip()

    try:
        parsed = json.loads(raw_llm_text)
    except json.JSONDecodeError as json_err:
        raise ValueError(f"Failed to parse Gemini AI response as JSON: {json_err}. Raw: {raw_llm_text[:200]}")

    items_list = parsed if isinstance(parsed, list) else (parsed.get("words") or parsed.get("items") or [])

    results: list[dict[str, Any]] = []
    for item in items_list:
        if not isinstance(item, dict):
            continue
        raw_word = str(item.get("word") or "").strip()
        clean_word = clean_companion_headword(raw_word)
        if not clean_word or len(clean_word) < 2:
            continue

        raw_pos = str(item.get("pos") or item.get("part_of_speech") or "noun").lower().strip()
        pos = normalize_pos(raw_pos)

        definition = str(item.get("definition") or "").strip()
        translation = clean_uzbek_text(
            str(item.get("translation") or item.get("uzbek_translation") or item.get("custom_translation") or "")
        )
        example_sentence = str(item.get("example_sentence") or item.get("example") or "").strip()

        clean_w, inferred_pos = infer_pos_and_clean_word(clean_word)
        final_pos = pos if pos != "phrase" else inferred_pos
        slug = re.sub(r"[^a-zA-Z0-9]+", "_", clean_w.lower()).strip("_")

        results.append({
            "word": clean_w,
            "pos": final_pos,
            "part_of_speech": final_pos,
            "definition": definition,
            "translation": translation,
            "uzbek_translation": translation,
            "custom_translation": translation,
            "example_sentence": example_sentence,
            "example": example_sentence,
            "phonetic": str(item.get("phonetic") or "").strip(),
            "audio_us_url": f"https://ssl.gstatic.com/dictionary/static/sounds/20200429/{slug}--_us_1.mp3",
            "ai_generated": True,
            "fallback_used": False,
            "source": "gemini_ai",
        })

    if not results:
        raise ValueError("Gemini AI could not identify any vocabulary entries in the uploaded file.")

    logger.info("Successfully extracted %d vocabulary items via Gemini AI multimodal extraction.", len(results))
    return results
